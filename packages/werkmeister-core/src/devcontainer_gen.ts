/**
 * Generated `.devcontainer/devcontainer.json` (SW-138): a Claude Code agent in a
 * dev container drives the host daemon on 3002 with this workspace's token.
 *
 * Everything container-only lives here, never in the shared `.mcp.json` (SW-115):
 * the MCP registration is made inside the container by `postCreateCommand`.
 * Overwritten on every init, like CLAUDE.md.
 */

import * as fs from "node:fs";
import * as path from "node:path";

export const DEVCONTAINER_FILE = ".devcontainer/devcontainer.json";
export const CLAUDE_HOME_VOLUME = "features-claude-home";

export interface DevcontainerOptions {
  workspaceName: string;
  workspaceRoot: string;
  workspacesRoot: string;
  reposRoot: string;
  home: string;
  port: number;
}

const HEADER =
  "// GENERATED by `werkmeister init-workspace` (packages/werkmeister-core/src/devcontainer_gen.ts)" +
  " — do not edit; rerun init-workspace.\n";

const bind = (p: string): string => `source=${p},target=${p},type=bind`;
const shellQuote = (s: string): string => `'${s.replaceAll("'", "'\\''")}'`;
const within = (child: string, parent: string): boolean => {
  const rel = path.relative(parent, child);
  return !rel.startsWith("..") && !path.isAbsolute(rel);
};

export function buildDevcontainer(opts: DevcontainerOptions): Record<string, unknown> {
  const claudeHome = `${opts.home}/.claude`;
  // A workspace outside the workspaces root (init on any folder) mounts by itself.
  const workspaceMount = within(opts.workspaceRoot, opts.workspacesRoot)
    ? opts.workspacesRoot
    : opts.workspaceRoot;
  // Docker refuses a duplicate mount target; a repos root already inside the workspace mount needs none.
  const repoMounts = within(opts.reposRoot, workspaceMount) ? [] : [bind(opts.reposRoot)];
  // Read at every connect, so a re-minted token reaches a running container; absolute because the helper's cwd varies.
  const headersHelper = `printf '{"Authorization":"Bearer %s"}' "$(cat ${JSON.stringify(path.join(opts.workspaceRoot, ".werkmeister/token"))})"`;
  const server = {
    type: "http",
    url: `http://host.docker.internal:${opts.port}/mcp`,
    headersHelper,
  };
  const postCreate = [
    // Docker creates HOME root-owned as the parent of the bind mounts.
    `sudo chown node:node "$HOME" "$HOME/.claude"`,
    "npm install -g @anthropic-ai/claude-code",
    // `mcp add-json` refuses an existing name, which a reused config keeps.
    "(claude mcp remove --scope user werkmeister >/dev/null 2>&1 || true)",
    // No feature header: the per-workspace token names the workspace (SW-184).
    `claude mcp add-json --scope user werkmeister ${shellQuote(JSON.stringify(server))}`,
  ].join(" && ");
  return {
    name: opts.workspaceName,
    image: "mcr.microsoft.com/devcontainers/javascript-node:22",
    features: { "ghcr.io/devcontainers/features/github-cli:1": {} },
    // Host paths, never /workspaces/...: each worktree's .git holds an absolute gitdir: into reposRoot.
    workspaceMount: bind(workspaceMount),
    workspaceFolder: opts.workspaceRoot,
    // One volume per workspace: the login and Claude state stay with their workspace.
    mounts: [
      ...repoMounts,
      `source=${CLAUDE_HOME_VOLUME}-${opts.workspaceName},target=${claudeHome},type=volume`,
    ],
    runArgs: ["--add-host=host.docker.internal:host-gateway"],
    containerEnv: {
      HOME: opts.home,
      GIT_CONFIG_COUNT: "1",
      GIT_CONFIG_KEY_0: "safe.directory",
      GIT_CONFIG_VALUE_0: "*",
    },
    remoteUser: "node",
    postCreateCommand: postCreate,
  };
}

export function writeWorkspaceDevcontainer(opts: DevcontainerOptions): string {
  const file = path.join(opts.workspaceRoot, DEVCONTAINER_FILE);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, HEADER + JSON.stringify(buildDevcontainer(opts), null, 2) + "\n");
  return file;
}
