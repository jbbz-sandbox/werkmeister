/**
 * The Codex adapter (SW-189): the generic MCP layout plus Codex hooks. hooks_gen.ts
 * writes the hooks into `.codex/hooks.json` (same shape as Claude's settings `hooks`);
 * this file registers the werkmeister MCP server in `.codex/config.toml`. Codex reads
 * both only once the folder is a trusted project and `/hooks` has approved each hook
 * (docs/harnesses.md § Codex). Sessions stay Claude's until SW-384.
 */
import * as fs from "node:fs";
import * as path from "node:path";

import { daemonPort } from "../../daemon_client.js";
import { warn } from "../../reporter.js";
import { mcpLayout } from "../mcp/index.js";
import type { HarnessLayout } from "../types.js";

export const CODEX_HOOKS_FILE = ".codex/hooks.json";
export const CODEX_CONFIG_FILE = ".codex/config.toml";
/** How Codex is started so its MCP calls carry this workspace's token (workspace scope, not machine). */
export const CODEX_LAUNCH = "WERKMEISTER_MCP_TOKEN=$(cat .werkmeister/token) codex";

const CONFIG_HEADER =
  "# Generated by werkmeister (harness: codex). Do not hand-edit; rerun `werkmeister workspace init`.";

export const codexLayout: HarnessLayout = {
  ...mcpLayout,
  id: "codex",
  hooks: { available: true },
  notice: () =>
    "\n## Harness\n\n" +
    "This workspace was generated for the `codex` harness. Werkmeister's tools come from the MCP " +
    `server \`werkmeister\` registered in \`${CODEX_CONFIG_FILE}\`, and its session-start context, ` +
    `standards gate, PR guard and agent state run as Codex hooks from \`${CODEX_HOOKS_FILE}\`. ` +
    "Codex loads both only once this folder is trusted and `/hooks` has approved each hook " +
    `(docs/harnesses.md in the werkmeister repo). Start Codex as \`${CODEX_LAUNCH}\`, so the ` +
    "server sees this workspace's token. Open PRs only with `werkmeister pr open`.\n",
};

export function codexConfigToml(): string {
  return [
    CONFIG_HEADER,
    "[mcp_servers.werkmeister]",
    // Loopback only: the tools are pre-approved, so the generated file must not follow WERKMEISTER_HOST.
    `url = "http://127.0.0.1:${daemonPort()}/mcp"`,
    "# A tokenless loopback call is machine-wide; the workspace token scopes the pre-approved tools to this workspace.",
    'bearer_token_env_var = "WERKMEISTER_MCP_TOKEN"',
    "# codex exec refuses non-read-only MCP tools unless pre-approved; the 300 s default cut off a first `up` (SW-188).",
    'default_tools_approval_mode = "approve"',
    "tool_timeout_sec = 1800",
    "",
  ].join("\n");
}

/** Write `.codex/config.toml`, unless a person wrote one (no generated header): then warn and keep it. */
export function writeCodexConfig(workspaceRoot: string): string {
  const file = path.join(workspaceRoot, CODEX_CONFIG_FILE);
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8").split("\n", 1)[0] !== CONFIG_HEADER) {
    warn(
      `${CODEX_CONFIG_FILE} was not written by werkmeister; left as is (add [mcp_servers.werkmeister], docs/harnesses.md)`,
    );
    return file;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, codexConfigToml());
  return file;
}
