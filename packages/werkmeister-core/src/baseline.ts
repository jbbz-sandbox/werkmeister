/**
 * Baseline services (SW-102): base services a feature is not changing, run in
 * `w9r-infra` from a digest-pinned registry image chosen in config.yaml
 * `infra.baseline`, so a machine with no cluster still has something to call.
 *
 * The images differ per machine, so they cannot live in the shipped
 * `shared-infra.yml`; like the k8s forwards, they go in a generated override
 * (`compose/baseline.override.yml` under `stateInfraRoot()`), rewritten on
 * every `connect`. A `{service}` ref reaches one only through that service's
 * `baseline_upstream` in services.yaml — this module never writes it.
 */

import * as fs from "node:fs";
import * as path from "node:path";

import { stringify as stringifyYaml } from "yaml";

import {
  type GlobalConfig,
  loadConfig,
  loadServices,
  type ServicesConfig,
  stateInfraRoot,
} from "./config.js";
import { info } from "./reporter.js";

export interface BaselineSpec {
  service: string;
  image: string;
  port: number;
  environment: Record<string, string>;
}

const PINNED_IMAGE = /@sha256:[0-9a-f]{64}$/;

function isDict(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** `infra.baseline` from config.yaml, checked against the registry. Throws on the first bad entry. */
export function baselineSpecs(config?: GlobalConfig, services?: ServicesConfig): BaselineSpec[] {
  const infra = (config ?? loadConfig())["infra"];
  const baseline = isDict(infra) ? infra["baseline"] : undefined;
  if (!isDict(baseline)) return [];
  const registry = services ?? loadServices();

  return Object.entries(baseline).map(([service, entry]) => {
    const where = `config.yaml infra.baseline.${service}`;
    const def = registry[service];
    if (!isDict(def)) {
      throw new Error(`${where}: no such service in services.yaml`);
    }
    const image = isDict(entry) ? entry["image"] : undefined;
    // Same rule as shared-infra.yml's pins (SEC-03): a tag can move under you.
    if (typeof image !== "string" || !PINNED_IMAGE.test(image)) {
      throw new Error(
        `${where}.image must be pinned as <image>@sha256:<digest>, got ${JSON.stringify(image)}. ` +
          "Resolve one with: docker pull <image>:<tag> && " +
          "docker inspect --format='{{index .RepoDigests 0}}' <image>:<tag>",
      );
    }
    const env = isDict(entry) ? (entry["environment"] ?? {}) : {};
    if (!isDict(env) || Object.values(env).some((v) => isDict(v) || Array.isArray(v))) {
      throw new Error(`${where}.environment must be a map of plain values`);
    }
    return {
      service,
      image,
      port: Number(def["internal_port"] ?? 3000),
      environment: Object.fromEntries(Object.entries(env).map(([k, v]) => [k, String(v)])),
    };
  });
}

/** The compose override `composeInvocation()` adds as a third `-f` when it exists. */
export function baselineOverridePath(): string {
  return path.join(stateInfraRoot(), "compose", "baseline.override.yml");
}

const _HEADER = [
  "# AUTO-GENERATED by `sandbox connect` from ~/.werkmeister/config.yaml infra.baseline — do not edit.",
  "# Merged over infra/compose/shared-infra.yml by every `docker compose` call the CLI makes.",
];

/**
 * Pure: the override for *specs*. The `baseline-` alias keeps a feature's own
 * local `<svc>` from resolving to the baseline on the shared network.
 */
export function renderBaselineOverride(specs: BaselineSpec[]): string {
  // ponytail: no healthcheck, limits or published ports — unknowable for an
  // arbitrary image; add a per-entry passthrough when someone needs one.
  const services = Object.fromEntries(
    specs.map((s) => {
      const alias = `baseline-${s.service}`;
      const net = { aliases: [alias] };
      return [
        alias,
        {
          image: s.image,
          container_name: `w9r-${alias}`,
          restart: "unless-stopped",
          ...(Object.keys(s.environment).length > 0 ? { environment: s.environment } : {}),
          // Both shared networks, as shared-infra.yml joins them (SW-93).
          networks: { "shared-network": net, "werkmeister-shared": net },
        },
      ];
    }),
  );
  return [..._HEADER, stringifyYaml({ services }, { aliasDuplicateObjects: false })].join("\n");
}

/** Write the override. Called by `sandbox connect` before `docker compose up`. */
export function generateBaselineOverride(quiet = false): void {
  const specs = baselineSpecs();
  const dest = baselineOverridePath();
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, renderBaselineOverride(specs));
  if (!quiet) {
    info(`Generated ${dest}`);
  }
}
