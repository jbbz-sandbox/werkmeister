/**
 * Service-registry generation from per-repo fragments.
 *
 * Each app repo commits `<repo>/.werkmeister/services.yaml` (legacy: `.sandbox/`) — a slice of the
 * registry schema holding only `services:`, `setup_services:` and
 * `infrastructure:`. This module scans `paths.repos_root` for those
 * fragments, merges them over the sandbox-owned defaults (archetypes, MCP
 * servers) and under the per-machine `~/.werkmeister/services.local.yaml`, and
 * writes `~/.werkmeister/services.yaml`. Nothing that READS the registry knows
 * any of this happened: readers keep loading the one generated file.
 *
 * Philosophy matches machine_setup.ts: `syncRegistry` reports through Step
 * objects and never throws; the pure functions throw RegistryError with a
 * message that names the file and key, and syncRegistry turns that into a
 * failing step.
 */

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";

import { parse as parseYaml, stringify as stringifyYaml } from "yaml";

import type { RepoEntry, ServiceEntry } from "./config.js";
import {
  DOT_DIRS,
  getReposRoot,
  sandboxHome,
  servicesLocalYamlPath,
  servicesYamlPath,
  workspacesRoot,
} from "./config.js";
import type { Step } from "./machine_setup.js";
import { REGISTRY_DEFAULTS, renderServicesLocalYaml, seedFile } from "./scaffold.js";

/** Where a new repo fragment goes, relative to its checkout root. */
export const FRAGMENT_REL = path.join(DOT_DIRS[0], "services.yaml");

/** *checkout*'s fragment, `.werkmeister/` first, then the legacy `.sandbox/` (SW-92); null when neither exists. */
export function fragmentPath(checkout: string): string | null {
  for (const d of DOT_DIRS) {
    const file = path.join(checkout, d, "services.yaml");
    if (fs.existsSync(file)) return file;
  }
  return null;
}

/** First line of every generated registry; its absence marks a hand-written file. */
export const GENERATED_MARKER = "# GENERATED by `sandbox registry sync` — do not edit.";

const FRAGMENT_KEYS = ["services", "setup_services", "infrastructure", "caches"] as const;

/** Top-level order of the generated document; local-only keys follow. */
const OUTPUT_ORDER = [
  "archetypes",
  "caches",
  "mcp_servers",
  "k8s_context",
  "services",
  "infrastructure",
  "setup_services",
  "repos",
];

export class RegistryError extends Error {}

type YamlMap = Record<string, unknown>;

/** `repos.<repo>` as the merge builds it. */
type MergedRepo = RepoEntry & { services: string[]; path_mappings: Record<string, string> };

/** The merged registry document; local-overlay keys such as `k8s_context` ride along untyped. */
export type MergedRegistry = {
  archetypes: YamlMap;
  caches: YamlMap;
  mcp_servers: YamlMap;
  services: Record<string, ServiceEntry>;
  infrastructure: Record<string, YamlMap>;
  setup_services: Record<string, ServiceEntry>;
  repos: Record<string, MergedRepo>;
  [key: string]: unknown;
};

export interface Fragment {
  /** Directory name under repos_root — the service's `repo:`. */
  repo: string;
  /** Absolute path of the fragment file, for messages. */
  path: string;
  doc: YamlMap;
}

export interface PlaceholderPaths {
  home: string;
  repos_root: string;
  workspaces_root: string;
  /** The tool's home folder: `~/.werkmeister`, or `~/.sandbox` until `werkmeister migrate` (SW-92). */
  werkmeister_home: string;
}

function isDict(value: unknown): value is YamlMap {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Every {@link fragmentPath} directly under *reposRoot* (main checkouts only), sorted by dir name. */
export function discoverFragments(reposRoot: string): Fragment[] {
  if (!fs.existsSync(reposRoot)) return [];
  const out: Fragment[] = [];
  for (const repo of fs.readdirSync(reposRoot).sort()) {
    const file = fragmentPath(path.join(reposRoot, repo));
    if (!file) continue;
    // A linked worktree (`.git` is a file) repeats its main checkout's fragment; every service would collide.
    if (fs.statSync(path.join(reposRoot, repo, ".git"), { throwIfNoEntry: false })?.isFile())
      continue;
    out.push(readFragment(repo, file));
  }
  return out;
}

function readFragment(repo: string, file: string): Fragment {
  let doc: unknown;
  try {
    doc = parseYaml(fs.readFileSync(file, "utf8"));
  } catch (e) {
    throw new RegistryError(`${file}: ${e instanceof Error ? e.message : String(e)}`);
  }
  return { repo, path: file, doc: isDict(doc) ? doc : {} };
}

const PLACEHOLDER = /\{\{\s*(home|repos_root|workspaces_root|werkmeister_home)\s*\}\}/g;

/** Expand every {@link PlaceholderPaths} key written as `{{key}}` in every string, at any depth. */
export function expandPlaceholders<T>(value: T, paths: PlaceholderPaths): T {
  if (typeof value === "string") {
    return value.replace(PLACEHOLDER, (_m, key: keyof PlaceholderPaths) => paths[key]) as T;
  }
  if (Array.isArray(value)) {
    return value.map((v) => expandPlaceholders(v, paths)) as T;
  }
  if (isDict(value)) {
    const out: YamlMap = {};
    for (const [k, v] of Object.entries(value)) out[k] = expandPlaceholders(v, paths);
    return out as T;
  }
  return value;
}

/** Maps merge recursively; scalars and lists from *over* replace. */
function deepMerge(base: YamlMap, over: YamlMap): YamlMap {
  const out: YamlMap = { ...base };
  for (const [k, v] of Object.entries(over)) {
    out[k] = isDict(v) && isDict(out[k]) ? deepMerge(out[k], v) : v;
  }
  return out;
}

/** Record *who* owns *key*; a different prior owner is a collision. */
function claim(owners: Map<string, string>, key: string, who: string, label: string): void {
  const prior = owners.get(key);
  if (prior !== undefined && prior !== who) {
    throw new RegistryError(`${label} is defined by both ${prior} and ${who}`);
  }
  owners.set(key, who);
}

export interface MergeOptions {
  defaults: { archetypes?: YamlMap; caches?: YamlMap; mcp_servers?: YamlMap };
  local: YamlMap;
  paths: PlaceholderPaths;
}

/**
 * Merge *fragments* into one registry document: defaults, then fragments
 * (collisions fail), then the local overlay (which may override anything).
 */
export function mergeRegistry(fragments: Fragment[], opts: MergeOptions): MergedRegistry {
  const merged: MergedRegistry = {
    archetypes: structuredClone(opts.defaults["archetypes"] ?? {}),
    caches: structuredClone(opts.defaults["caches"] ?? {}),
    mcp_servers: structuredClone(opts.defaults["mcp_servers"] ?? {}),
    services: {},
    infrastructure: {},
    setup_services: {},
    repos: {},
  };
  const owners = new Map<string, string>();
  // A fragment may add caches but not redefine a built-in: that is a collision, like a service name.
  for (const name of Object.keys(merged.caches)) owners.set(`caches/${name}`, "werkmeister");

  for (const fragment of fragments) {
    const doc = expandPlaceholders(fragment.doc, opts.paths);
    for (const key of Object.keys(doc)) {
      if (
        key.startsWith("x-") ||
        key === "repo" ||
        (FRAGMENT_KEYS as readonly string[]).includes(key)
      )
        continue;
      throw new RegistryError(
        `${fragment.path}: unexpected top-level key \`${key}\` — a fragment may only ` +
          `contain ${FRAGMENT_KEYS.join(", ")}, repo (and x-* anchor blocks)`,
      );
    }
    // `repo:` is settings for the fragment's repo as a whole (ship detection,
    // docs/workspace-lifecycle.md), not a map of named entries like the sections below.
    if (doc["repo"] !== undefined) {
      if (!isDict(doc["repo"]))
        throw new RegistryError(`${fragment.path}: \`repo:\` must be a map`);
      Object.assign(
        (merged["repos"][fragment.repo] ??= { services: [], path_mappings: {} }),
        doc["repo"],
      );
    }
    for (const section of FRAGMENT_KEYS) {
      const entries = doc[section] ?? {};
      if (!isDict(entries)) {
        throw new RegistryError(`${fragment.path}: \`${section}:\` must be a map`);
      }
      for (const [name, raw] of Object.entries(entries)) {
        if (!isDict(raw)) {
          throw new RegistryError(`${fragment.path}: \`${section}.${name}\` must be a map`);
        }
        claim(owners, `${section}/${name}`, fragment.repo, `${section}.${name}`);
        let entry: ServiceEntry = raw;
        if (section === "services" || section === "setup_services") {
          if (raw["repo"] !== undefined && raw["repo"] !== fragment.repo) {
            throw new RegistryError(
              `${fragment.path}: ${section}.${name} says repo: ${raw["repo"]} but lives in ${fragment.repo}`,
            );
          }
          entry = { repo: fragment.repo, ...raw };
        }
        if (section === "services") {
          if (entry["port_offset"] !== undefined) {
            claim(
              owners,
              `port_offset/${entry["port_offset"]}`,
              `${fragment.repo}:${name}`,
              `port_offset ${entry["port_offset"]}`,
            );
          }
          const repoEntry = (merged["repos"][fragment.repo] ??= {
            services: [],
            path_mappings: {},
          });
          repoEntry.services.push(name);
          const svcPath = String(entry["path"] ?? ".").replace(/^\/+|\/+$/g, "");
          if (svcPath !== "" && svcPath !== ".") repoEntry.path_mappings[svcPath] = name;
        }
        if (
          (section === "services" || section === "infrastructure") &&
          entry["k8s_forward_port"] !== undefined
        ) {
          claim(
            owners,
            `k8s_forward_port/${entry["k8s_forward_port"]}`,
            `${fragment.repo}:${name}`,
            `k8s_forward_port ${entry["k8s_forward_port"]}`,
          );
        }
        merged[section][name] = entry;
      }
    }
  }

  return deepMerge(merged, opts.local) as MergedRegistry;
}

/** The generated file: marker header, then the document in OUTPUT_ORDER. */
export function renderRegistry(
  merged: MergedRegistry,
  sources: string[],
  localPath: string,
): string {
  const ordered: YamlMap = {};
  for (const key of OUTPUT_ORDER) if (key in merged) ordered[key] = merged[key];
  for (const key of Object.keys(merged)) if (!(key in ordered)) ordered[key] = merged[key];
  const header = [
    GENERATED_MARKER,
    "# Edit a repo's .werkmeister/services.yaml fragment, or the machine overrides file, then",
    "# run `sandbox registry sync` (or `sandbox setup`). Regenerated from:",
    ...sources.map((s) => `# Source: ${s}`),
    `# Machine overrides: ${localPath}`,
    "",
  ].join("\n");
  return header + stringifyYaml(ordered, { lineWidth: 0 });
}

/**
 * The `k8s_context` of a HAND-WRITTEN registry at *registryPath*, or null for
 * a missing, generated, unparsable or context-less file. An existing developer
 * upgrading onto fragments keeps the cluster they already point at, rather
 * than being silently reset to the default — intercepting the wrong cluster is
 * the failure `getK8sContext` exists to prevent.
 */
export function inheritedK8sContext(registryPath: string): string | null {
  if (!fs.existsSync(registryPath)) return null;
  const text = fs.readFileSync(registryPath, "utf8");
  if (text.startsWith(GENERATED_MARKER)) return null;
  try {
    const doc = parseYaml(text);
    const ctx = isDict(doc) ? doc["k8s_context"] : undefined;
    return typeof ctx === "string" && ctx.trim() ? ctx.trim() : null;
  } catch {
    return null;
  }
}

/** `section.name` for every entry of *oldText*'s three fragment sections that *merged* lacks. */
function orphanedEntries(oldText: string, merged: MergedRegistry): string[] {
  let old: unknown;
  try {
    old = parseYaml(oldText);
  } catch {
    return [];
  }
  if (!isDict(old)) return [];
  const orphans: string[] = [];
  for (const section of FRAGMENT_KEYS) {
    const entries = old[section];
    if (!isDict(entries)) continue;
    for (const name of Object.keys(entries)) {
      if (!(name in (merged[section] ?? {}))) orphans.push(`${section}.${name}`);
    }
  }
  return orphans;
}

export interface SyncRegistryOptions {
  /** Defaults to `paths.repos_root`. */
  reposRoot?: string;
  /** Report what would happen; write nothing. */
  checkOnly?: boolean;
  /** Clock for the backup suffix (tests). */
  now?: () => number;
}

function placeholderPaths(): PlaceholderPaths {
  return {
    home: os.homedir(),
    repos_root: getReposRoot(),
    workspaces_root: workspacesRoot(),
    werkmeister_home: sandboxHome(),
  };
}

function readLocalOverlay(localPath: string): YamlMap {
  if (!fs.existsSync(localPath)) return {};
  let doc: unknown;
  try {
    doc = parseYaml(fs.readFileSync(localPath, "utf8"));
  } catch (e) {
    throw new RegistryError(`${localPath}: ${e instanceof Error ? e.message : String(e)}`);
  }
  if (doc === null || doc === undefined) return {};
  if (!isDict(doc)) throw new RegistryError(`${localPath}: must be a map of registry keys`);
  return doc;
}

/**
 * The registry `syncRegistry` would build if *repo*'s main checkout held
 * *worktree*'s fragment, so the pre-PR gate tests a branch with the commands
 * it ships rather than main's (SW-25). Writes nothing: the shared registry
 * stays main's, so other workspaces are unaffected. Null when the worktree has
 * no fragment; throws RegistryError like mergeRegistry.
 */
export function branchRegistry(
  repo: string,
  worktree: string,
  reposRoot: string = getReposRoot(),
): MergedRegistry | null {
  const file = fragmentPath(worktree);
  if (!file) return null;
  const fragments = discoverFragments(reposRoot).filter((f) => f.repo !== repo);
  fragments.push(readFragment(repo, file));
  return mergeRegistry(fragments, {
    defaults: REGISTRY_DEFAULTS,
    local: readLocalOverlay(servicesLocalYamlPath()),
    paths: placeholderPaths(),
  });
}

/**
 * Regenerate `~/.werkmeister/services.yaml` from every fragment under repos_root.
 *
 * One Step, label `config services.yaml`, matching the other registry files'
 * steps in machine_setup. Never throws: a bad fragment or a collision is a
 * failing step whose detail is the RegistryError message.
 */
export function syncRegistry(opts: SyncRegistryOptions = {}): Step[] {
  const label = "config services.yaml";
  const reposRoot = opts.reposRoot ?? getReposRoot();
  const target = servicesYamlPath();
  const localPath = servicesLocalYamlPath();

  let fragments: Fragment[];
  let merged: MergedRegistry;
  let text: string;
  // A standalone `sandbox registry sync` on a machine that never ran the new
  // setup would otherwise merge with no overlay and silently drop k8s_context
  // (which `sandbox intercept` requires). Seed the overlay the way setup does;
  // seedFile never overwrites, so an existing file is untouched.
  let seededLocal = "";
  try {
    if (!opts.checkOnly && !fs.existsSync(localPath)) {
      const context = inheritedK8sContext(target) ?? "orbstack";
      seedFile(localPath, renderServicesLocalYaml(context));
      seededLocal = `; seeded ${localPath} (k8s_context: ${context} — edit there)`;
    }
    fragments = discoverFragments(reposRoot);
    if (fragments.length === 0) {
      return [
        {
          label,
          ok: false,
          detail:
            `no ${FRAGMENT_REL} found under ${reposRoot} — clone your team's repos there and ` +
            "re-run `sandbox setup` (or answer yes to the demo apps)",
        },
      ];
    }
    merged = mergeRegistry(fragments, {
      defaults: REGISTRY_DEFAULTS,
      local: readLocalOverlay(localPath),
      paths: placeholderPaths(),
    });
    text = renderRegistry(
      merged,
      fragments.map((f) => f.path),
      localPath,
    );
  } catch (e) {
    return [{ label, ok: false, detail: e instanceof Error ? e.message : String(e) }];
  }

  const sources = `${fragments.length} fragment${fragments.length === 1 ? "" : "s"}`;
  const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (existing === text) {
    return [{ label, ok: true, detail: `up to date (${sources}) at ${target}${seededLocal}` }];
  }
  if (opts.checkOnly) {
    return [
      {
        label,
        ok: false,
        detail:
          existing === null
            ? `missing — would generate ${target} from ${sources}`
            : `drift — would regenerate ${target} from ${sources}`,
      },
    ];
  }

  let note = "";
  if (existing !== null && !existing.startsWith(GENERATED_MARKER)) {
    const stamp = Math.floor((opts.now ?? Date.now)() / 1000);
    const backup = `${target}.bak-${stamp}`;
    fs.copyFileSync(target, backup);
    note = `; hand-written registry backed up to ${backup}`;
    // Entries the fragments do not carry vanish from the active registry; name
    // them so the developer knows what to move into a fragment (or the overlay).
    const orphans = orphanedEntries(existing, merged);
    if (orphans.length) note += `; not in any fragment: ${orphans.join(", ")}`;
  }
  try {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
  } catch (e) {
    return [{ label, ok: false, detail: `could not write ${target}: ${e}` }];
  }
  return [{ label, ok: true, detail: `generated ${target} from ${sources}${note}${seededLocal}` }];
}
