// The container sees the host's paths and the host daemon, and nothing it
// needs leaks into the .mcp.json host sessions share (SW-138, SW-115).

import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { test } from "node:test";

import {
  buildDevcontainer,
  DEVCONTAINER_FILE,
  writeWorkspaceDevcontainer,
} from "./dist/devcontainer_gen.js";

const OPTS = {
  workspaceName: "ws-1",
  workspaceRoot: "/Users/u/features/ws-1",
  workspacesRoot: "/Users/u/features",
  reposRoot: "/Users/u/repos",
  home: "/Users/u",
  port: 3002,
};

test("mounts, env and add-host use the host's paths", () => {
  const dc = buildDevcontainer(OPTS);
  assert.equal(dc.workspaceMount, "source=/Users/u/features,target=/Users/u/features,type=bind");
  assert.equal(dc.workspaceFolder, "/Users/u/features/ws-1");
  assert.deepEqual(dc.mounts, [
    "source=/Users/u/repos,target=/Users/u/repos,type=bind",
    "source=features-claude-home-ws-1,target=/Users/u/.claude,type=volume",
  ]);
  assert.deepEqual(dc.containerEnv, {
    HOME: "/Users/u",
    GIT_CONFIG_COUNT: "1",
    GIT_CONFIG_KEY_0: "safe.directory",
    GIT_CONFIG_VALUE_0: "*",
  });
  assert.ok(dc.runArgs.includes("--add-host=host.docker.internal:host-gateway"));
  assert.doesNotMatch(JSON.stringify(dc), /\/workspaces\//);
});

test("registers werkmeister per workspace, reading its token file at every connect", () => {
  const cmd = buildDevcontainer(OPTS).postCreateCommand;
  const json = cmd
    .match(/claude mcp add-json --scope user werkmeister '(.*)'$/)[1]
    .replaceAll("'\\''", "'");
  assert.deepEqual(JSON.parse(json), {
    type: "http",
    url: "http://host.docker.internal:3002/mcp",
    headersHelper:
      'printf \'{"Authorization":"Bearer %s"}\' "$(cat "/Users/u/features/ws-1/.werkmeister/token")"',
  });
  // A reused config keeps the entry, where a bare `mcp add-json` would refuse the name.
  assert.ok(
    cmd.indexOf("claude mcp remove --scope user werkmeister") < cmd.indexOf("claude mcp add-json"),
  );
  assert.doesNotMatch(cmd, /X-Werkmeister-Feature|mcp-token|--scope local|--header/);
});

test("one mount when the repos root equals the workspaces root", () => {
  const dc = buildDevcontainer({ ...OPTS, reposRoot: "/Users/u/features" });
  assert.equal(dc.workspaceMount, "source=/Users/u/features,target=/Users/u/features,type=bind");
  assert.deepEqual(dc.mounts, [
    "source=features-claude-home-ws-1,target=/Users/u/.claude,type=volume",
  ]);
});

test("a workspace outside the workspaces root is mounted by itself", () => {
  const dc = buildDevcontainer({ ...OPTS, workspaceRoot: "/tmp/ws-x" });
  assert.equal(dc.workspaceMount, "source=/tmp/ws-x,target=/tmp/ws-x,type=bind");
  assert.equal(dc.workspaceFolder, "/tmp/ws-x");
  assert.equal(dc.mounts[0], "source=/Users/u/repos,target=/Users/u/repos,type=bind");
});

test("a non-default daemon port reaches the URL", () => {
  const cmd = buildDevcontainer({ ...OPTS, port: 4555 }).postCreateCommand;
  assert.match(cmd, /host\.docker\.internal:4555\/mcp/);
});

test("writes a headed JSONC file, overwrites it, and leaves .mcp.json alone", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "devcontainer-gen-"));
  const mcp = '{"mcpServers":{"mine":{"command":"x"}}}\n';
  fs.writeFileSync(path.join(root, ".mcp.json"), mcp);
  const opts = { ...OPTS, workspaceRoot: root };

  writeWorkspaceDevcontainer(opts);
  const file = writeWorkspaceDevcontainer(opts);

  assert.equal(file, path.join(root, DEVCONTAINER_FILE));
  const [header, ...rest] = fs.readFileSync(file, "utf8").split("\n");
  assert.match(header, /^\/\/ GENERATED by `werkmeister init-workspace`/);
  assert.deepEqual(JSON.parse(rest.join("\n")), buildDevcontainer(opts));
  assert.equal(fs.readFileSync(path.join(root, ".mcp.json"), "utf8"), mcp);
});
