/**
 * Generate the k8s port-forward table from services.yaml (the single source
 * of truth) into the two files that consume it at runtime:
 *
 * 1. `infra/compose/k8s-port-forward/tmp/forwards` — a pipe-delimited data file
 *    the container's entrypoint.sh reads to build its `FORWARDS` array. Written
 *    fresh on every `sandbox connect` (the tmp/ dir is gitignored, like the
 *    pinned kubeconfig).
 *
 * 2. `infra/compose/shared-infra.yml` — the `k8s-forwards` service's published
 *    `ports:` and network `aliases:` are regenerated in place between
 *    `# >>> GENERATED` / `# <<< GENERATED` markers.
 *
 * All three (entrypoint data file, published ports, network aliases) derive from
 * the same `forwardSpecs()` list so they cannot drift.
 */

import * as fs from "node:fs";
import * as path from "node:path";

import {
  forwardSpecs as specsFrom,
  type ForwardSpec,
  infraRoot,
  loadInfrastructure,
  loadServices,
} from "./config.js";
import { info } from "./reporter.js";

const _PORTS_START = "# >>> GENERATED k8s-forward ports (from services.yaml — do not edit; `sandbox connect` regenerates)";
const _PORTS_END = "# <<< GENERATED k8s-forward ports";
const _ALIASES_START = "# >>> GENERATED k8s-forward aliases (from services.yaml — do not edit; `sandbox connect` regenerates)";
const _ALIASES_END = "# <<< GENERATED k8s-forward aliases";

/**
 * The forward table, from the shared registry semantics in
 * `sandbox-core/config` — the dashboard's health checks read the same table,
 * so it is defined once. Loading the registry (and failing loud when it is
 * missing) stays here; the parse does not.
 */
export function forwardSpecs(
  services?: Record<string, any> | null,
  infrastructure?: Record<string, any> | null,
): ForwardSpec[] {
  return specsFrom(services ?? loadServices(), infrastructure ?? loadInfrastructure());
}

export type { ForwardSpec };

/** Pipe-delimited rows for the entrypoint's FORWARDS array. */
export function buildForwardRows(
  services?: Record<string, any> | null,
  infrastructure?: Record<string, any> | null,
): string[] {
  // Row format the entrypoint parses: name|listen|remote|namespace|pod_prefix|health
  return forwardSpecs(services, infrastructure).map(
    (s) => `${s.name}|${s.listen}|${s.remote}|${s.ns}|${s.prefix}|${s.health}`,
  );
}

function forwardsFilePath(): string {
  return path.join(infraRoot(), "compose", "k8s-port-forward", "tmp", "forwards");
}

/** Write the entrypoint's forward data file. Returns the path written. */
export function generateForwardsFile(dest?: string | null): string {
  dest = dest ?? forwardsFilePath();
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const body = [
    "# AUTO-GENERATED by `sandbox connect` from ~/.sandbox/services.yaml — do not edit.",
    "# Format: name|listen_port|remote_port|namespace|pod_prefix|health_path",
    ...buildForwardRows(),
    "",
  ].join("\n");
  fs.writeFileSync(dest, body);
  return dest;
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Replace the lines between a start/end marker pair, preserving each
 * marker's own indentation. Throws if the markers are missing.
 */
function replaceBetween(text: string, start: string, end: string, newLines: string[]): string {
  const pattern = new RegExp(
    "(^([ \\t]*)" + escapeRegExp(start) + "[ \\t]*\\n)(.*?)(^[ \\t]*" + escapeRegExp(end) + "[ \\t]*$)",
    "smd",
  );
  const m = pattern.exec(text) as (RegExpExecArray & { indices?: Array<[number, number]> }) | null;
  if (!m || !m.indices) {
    throw new Error(`Markers not found in shared-infra.yml: '${start}' … '${end}'`);
  }
  const body = newLines.map((line) => line + "\n").join("");
  return text.slice(0, m.indices[3][0]) + body + text.slice(m.indices[4][0]);
}

function sharedInfraPath(): string {
  return path.join(infraRoot(), "compose", "shared-infra.yml");
}

/**
 * Pure: return shared-infra.yml text with its ports:/aliases: GENERATED
 * regions rewritten from services.yaml. Throws if either marker is absent.
 * Read-only — used by the drift test to detect drift without mutating the
 * committed file.
 */
export function renderSharedInfraForwards(original: string): string {
  const specs = forwardSpecs();
  // ports: are indented 6 spaces inside the k8s-forwards service block.
  const portLines = specs.map((s) => `      - "${s.listen}:${s.listen}"   # ${s.name}`);
  // aliases: are indented 10 spaces under networks.shared-network.aliases.
  const aliasLines = specs.map((s) => `          - k8s-${s.name}`);

  let updated = replaceBetween(original, _PORTS_START, _PORTS_END, portLines);
  updated = replaceBetween(updated, _ALIASES_START, _ALIASES_END, aliasLines);
  return updated;
}

/**
 * Rewrite the ports:/aliases: GENERATED regions of shared-infra.yml from
 * services.yaml. Returns true if the file content changed (idempotent no-op
 * when already in sync). Throws if either marker pair is absent.
 */
export function regenerateSharedInfraForwards(filePath?: string | null): boolean {
  filePath = filePath ?? sharedInfraPath();
  const original = fs.readFileSync(filePath, "utf8");
  const updated = renderSharedInfraForwards(original);
  if (updated !== original) {
    fs.writeFileSync(filePath, updated);
    return true;
  }
  return false;
}

/**
 * Generate both consumers of the forward table. Called from sandbox connect
 * before `docker compose up`.
 */
export function generateK8sForwards(quiet = false): void {
  generateForwardsFile();
  const changed = regenerateSharedInfraForwards();
  if (!quiet) {
    info("Generated k8s-port-forward/tmp/forwards" + (changed ? "; updated shared-infra.yml ports/aliases" : ""));
  }
}
