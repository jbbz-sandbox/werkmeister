/**
 * Forward-table generation for `infrastructure:` entries.
 *
 * buildForwardRows() takes services + infrastructure as explicit args, so the
 * generation logic is testable with fixtures — no config/proc mocking needed.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { buildForwardRows, renderK8sForwardsOverride } from "werkmeister-core/k8s_forwards";
import { parse as parseYaml } from "yaml";

describe("buildForwardRows — infrastructure forwards", () => {
  it("emits a pipe-delimited row per infra entry that declares k8s_forward_port", () => {
    const infra = {
      redis: {
        k8s_forward_port: 9050,
        internal_port: 6379,
        k8s_namespace: "default",
        k8s_pod_prefix: "redis",
        health_endpoint: "",
      },
      postgres: {
        k8s_forward_port: 9051,
        internal_port: 5432,
        k8s_namespace: "default",
        k8s_pod_prefix: "postgres",
        health_endpoint: "",
      },
    };
    const rows = buildForwardRows({}, infra);
    // name|listen|remote|namespace|pod_prefix|health
    expect(rows).toEqual([
      "redis|9050|6379|default|redis|",
      "postgres|9051|5432|default|postgres|",
    ]);
  });

  it("skips infra entries without k8s_forward_port", () => {
    const infra = {
      redis: {
        k8s_forward_port: 9050,
        internal_port: 6379,
        k8s_namespace: "default",
        k8s_pod_prefix: "redis",
        health_endpoint: "",
      },
      search: { note: "external, not forwarded" },
    };
    const rows = buildForwardRows({}, infra);
    expect(rows).toEqual(["redis|9050|6379|default|redis|"]);
  });

  it("skips a service or infra entry that declares baseline_upstream, even with k8s_forward_port (SW-102)", () => {
    const services = {
      backend: {
        k8s_forward_port: 9052,
        internal_port: 3000,
        baseline_upstream: "baseline-backend:3000",
      },
      frontend: { k8s_forward_port: 9053, internal_port: 3000 },
    };
    const infra = {
      redis: { k8s_forward_port: 9050, internal_port: 6379, baseline_upstream: "10.0.0.5:6379" },
    };
    expect(buildForwardRows(services, infra)).toEqual(["frontend|9053|3000|||"]);
  });

  it("returns no rows when there is no forwarded infrastructure", () => {
    expect(buildForwardRows({}, {})).toEqual([]);
  });

  it("forwards services to their pod containerPort (internal_port), not the Service port", () => {
    const services = {
      backend: {
        k8s_forward_port: 9052,
        internal_port: 3000,
        k8s_port: 80,
        k8s_namespace: "default",
        k8s_pod_prefix: "backend",
        health_endpoint: "/health",
      },
      frontend: {
        k8s_forward_port: 9053,
        internal_port: 3000,
        k8s_port: 8080,
        k8s_namespace: "default",
        k8s_pod_prefix: "frontend",
        health_endpoint: "/",
      },
    };
    expect(buildForwardRows(services, {})).toEqual([
      "backend|9052|3000|default|backend|/health",
      "frontend|9053|3000|default|frontend|/",
    ]);
  });
});

describe("renderK8sForwardsOverride", () => {
  const specs = [
    {
      name: "backend",
      listen: 9052,
      remote: 3000,
      ns: "default",
      prefix: "backend",
      health: "/health",
    },
    { name: "redis", listen: 9050, remote: 6379, ns: "default", prefix: "redis", health: "" },
  ];

  it("renders one published port and one network alias per forward", () => {
    expect(renderK8sForwardsOverride(specs)).toBe(
      [
        "# AUTO-GENERATED by `sandbox connect` from ~/.werkmeister/services.yaml — do not edit.",
        "# Merged over infra/compose/shared-infra.yml by every `docker compose` call the CLI makes.",
        "services:",
        "  k8s-forwards:",
        "    ports:",
        '      - "9052:9052"   # backend',
        '      - "9050:9050"   # redis',
        "    networks:",
        "      shared-network:",
        "        aliases:",
        "          - k8s-backend",
        "          - k8s-redis",
        "      werkmeister-shared:",
        "        aliases:",
        "          - k8s-backend",
        "          - k8s-redis",
        "",
      ].join("\n"),
    );
  });

  it("renders a valid empty service when there are no forwards", () => {
    expect(renderK8sForwardsOverride([])).toBe(
      [
        "# AUTO-GENERATED by `sandbox connect` from ~/.werkmeister/services.yaml — do not edit.",
        "# Merged over infra/compose/shared-infra.yml by every `docker compose` call the CLI makes.",
        "services:",
        "  k8s-forwards: {}",
        "",
      ].join("\n"),
    );
  });
});

describe("shipped shared-infra.yml", () => {
  const composeFile = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../../../infra/compose/shared-infra.yml",
  );
  const text = fs.readFileSync(composeFile, "utf8");

  it("carries no GENERATED regions — the override file owns ports and aliases", () => {
    expect(text).not.toContain("GENERATED");
    expect(text).not.toMatch(/^\s+- "9\d{3}:9\d{3}"/m);
    expect(text).not.toMatch(/^\s+- k8s-(backend|frontend|redis|postgres)$/m);
  });

  it("mounts every generated file from ${SANDBOX_STATE_DIR}", () => {
    expect(text).toContain("${SANDBOX_STATE_DIR}/k8s-port-forward/kubeconfig:/tmp/kubeconfig:ro");
    expect(text).toContain("${SANDBOX_STATE_DIR}/k8s-port-forward/forwards:/tmp/forwards:ro");
    expect(text).toContain("${SANDBOX_STATE_DIR}/proxy/Caddyfile:/etc/caddy/Caddyfile:ro");
    expect(text).toContain("${SANDBOX_STATE_DIR}/proxy/features.json:/srv/features.json:ro");
    expect(text).not.toContain("./k8s-port-forward/tmp/");
    expect(text).not.toContain("../proxy/Caddyfile");
  });

  // SW-100: docker must create a nested bind's mountpoint inside the outer bind's
  // host dir, which fails on a :ro mount and litters the checkout otherwise.
  it("nests no bind under another bind's target", () => {
    const doc = parseYaml(text) as {
      services: Record<string, { volumes?: (string | { type?: string; target?: string })[] }>;
    };
    const nested: string[] = [];
    for (const [name, svc] of Object.entries(doc.services)) {
      const targets = (svc.volumes ?? []).flatMap((v) => {
        if (typeof v !== "string") return v.type === "bind" && v.target ? [v.target] : [];
        // The target is the first absolute part: a ${VAR:-default} source has its own colon.
        const [source = "", ...rest] = v.split(":");
        const target = rest.find((part) => part.startsWith("/"));
        // Named volumes have a bare-name source; binds start with ., / , ~ or ${.
        return /^[./~$]/.test(source) && target ? [target] : [];
      });
      for (const inner of targets) {
        for (const outer of targets) {
          if (inner.startsWith(outer.replace(/\/*$/, "/")))
            nested.push(`${name}: ${inner} under ${outer}`);
        }
      }
    }
    expect(nested).toEqual([]);
  });

  // SW-93: features up'd before the rename are still on sandbox-shared.
  it("joins every service to both shared networks under the same aliases", () => {
    const doc = parseYaml(text) as {
      networks: Record<string, { name: string }>;
      services: Record<string, { networks?: Record<string, unknown> }>;
    };
    expect(doc.networks["shared-network"].name).toBe("sandbox-shared");
    expect(doc.networks["werkmeister-shared"].name).toBe("werkmeister-shared");
    const networked = Object.values(doc.services).filter((svc) => svc.networks);
    expect(networked.length).toBeGreaterThan(0);
    for (const svc of networked) {
      expect(svc.networks?.["werkmeister-shared"]).toEqual(svc.networks?.["shared-network"]);
    }
  });
});
