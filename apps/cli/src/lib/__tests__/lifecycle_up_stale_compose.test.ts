/**
 * `up` only warned when compose.yml predated the template or registry, so a
 * template change (SW-32's idle containers) never reached existing workspaces
 * without a re-init. Every collaborator of `up` is mocked except the compose
 * staleness check and generation, which run for real against the template.
 */

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { COMPOSE_FILE } from "werkmeister-core/compose_file";
import type { Reporter } from "werkmeister-core/reporter";
import { withReporter } from "werkmeister-core/reporter";

vi.mock("werkmeister-core/caddy", () => ({
  isCaddyRunning: () => true,
  reloadCaddy: async () => {},
  startCaddy: vi.fn(),
}));
vi.mock("werkmeister-core/config", async (importOriginal) => ({
  ...(await importOriginal<object>()),
  loadPorts: () => ({ slots: { start: 11000, size: 20 } }),
  loadServices: () => ({}),
  loadSetupServices: () => ({}),
}));
vi.mock("werkmeister-core/feature_routing", () => ({ loadFeatureRouters: () => ({}) }));
vi.mock("werkmeister-core/generate", async (importOriginal) => ({
  ...(await importOriginal<object>()),
  generateCaddyfile: async () => {},
  generateSupergraphConfig: () => null,
  writeServiceSecretEnvs: () => {},
}));
vi.mock("werkmeister-core/k8s", () => ({ ensurePortForwardsHealthy: () => "healthy" }));
vi.mock("werkmeister-core/secrets", () => ({
  getSecretsPath: () => "/nonexistent/secrets.yaml",
  loadSecrets: () => ({}),
  resolveSecrets: () => ({ byService: {}, missing: [] }),
}));
vi.mock("werkmeister-core/slots", () => ({
  allocateSlot: async () => 3,
  getPortRange: () => [3300, 3399],
  getServicePort: () => 3300,
}));

import { up } from "werkmeister-core/lifecycle";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const quiet: Reporter = { passthrough: false, emit: () => {} };
let root: string;
let compose: string;

beforeEach(() => {
  process.env.SANDBOX_ROOT = repoRoot;
  root = fs.mkdtempSync(path.join(os.tmpdir(), "up-stale-"));
  compose = path.join(root, COMPOSE_FILE);
  fs.writeFileSync(compose, "# from an older template\nservices: {}\n");
  // Slot 3 matches allocateSlot, so `up` takes the unchanged-slot path.
  fs.writeFileSync(path.join(root, ".env"), "SANDBOX_SLOT=3\nSERVICES=\n");
  fs.mkdirSync(path.join(root, ".sandbox"));
  fs.writeFileSync(path.join(root, ".sandbox", "workspace.yml"), "context_strategy: icm\n");
});
afterEach(() => {
  fs.rmSync(root, { recursive: true, force: true });
});

describe("lifecycle.up with a stale compose", () => {
  it("regenerates it instead of only warning", async () => {
    const result = await withReporter(quiet, () => up("demo", root));
    expect(result.staleCompose).toBe(true);
    const text = fs.readFileSync(compose, "utf8");
    expect(text).toContain("# Generated by: sandbox up");
    expect(text).not.toContain("older template");
  });

  it("leaves a current compose alone", async () => {
    await withReporter(quiet, () => up("demo", root));
    const mtime = fs.statSync(compose).mtimeMs;
    const result = await withReporter(quiet, () => up("demo", root));
    expect(result.staleCompose).toBe(false);
    expect(fs.statSync(compose).mtimeMs).toBe(mtime);
  });
});
